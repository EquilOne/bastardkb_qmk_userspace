/*
 * Keymap decoded 1:1 from an Argos configuration export
 * (argos_config.json, keycodes[8][60], 10 rows x 6 cols, right half mirrored).
 * Matrix-to-LAYOUT mapping follows keyboards/bastardkb/scylla/info.json
 * (LAYOUT_split_4x6_5, 58 keys; thumb keys live in matrix rows 4 and 9).
 *
 * Runtime state that is deliberately NOT hardcoded here (it lives in EEPROM
 * and survives re-flashing, owned by the Argos community module):
 *   - macro contents for QK_MACRO_0..4   (argos.c / dynamic macros)
 *   - no tap dances configured (all 50 Argos tap-dance slots are empty)
 *   - combo 0: Space + Backspace -> Tab, enabled (argos_combo.c / EEPROM)
 *   - per-layer RGB colors                (argos_rgb.c)
 *   - tapping term 180 ms, combo term 50 ms, flow-tap term 150 ms (argos.c)
 */

#include QMK_KEYBOARD_H

/* Per-layer RGB colors, driven from this keymap via layer_state_set_user():
 *   layer 0 "base"    :   0, 135, 205   (steel blue)
 *   layer 1 "nav/sym" : 209,  98,  89   (salmon)
 *   layer 2 "extra"   :  84, 181, 209   (sky blue)
 *   layer 3 "layer 3" :   0,  70, 176   (blue)
 *   layer 4 "layer 4" :   0, 199,  70   (green 2)
 *   layer 5 "layer 5" :  76,   0,  70   (plum)
 *   layer 6 "layer 6" :  70,   0,  43   (dark red)
 *   layer 7 "layer 7" :  70,   0,  23   (darker red)
 *
 * If the Argos community module (keymap.json declares it) is still enabled,
 * argos_rgb.c repaints its EEPROM-stored colors every frame from
 * rgb_matrix_indicators_advanced_argos() and the two will conflict.  The
 * module's EEPROM palette must be cleared, or the module disabled.
 */

#ifdef RGB_MATRIX_ENABLE
// Per-layer solid colors, driven from the keymap (overrides Argos EEPROM palette).
static const uint8_t g_layer_rgb[8][3] = {
    {0, 135, 205}, {209, 98, 89}, {84, 181, 209}, {0, 70, 176}, {0, 199, 70}, {76, 0, 70}, {70, 0, 43}, {70, 0, 23},
};

layer_state_t layer_state_set_user(layer_state_t state) {
    uint8_t layer = get_highest_layer(state);
    if (layer < 8) {
        rgb_matrix_set_color_all(g_layer_rgb[layer][0], g_layer_rgb[layer][1], g_layer_rgb[layer][2]);
    }
    return state;
}
#endif

